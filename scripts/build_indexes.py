#!/usr/bin/env python3
"""Regenerate datasets/README.md and the pages under datasets/index/.

Output depends only on the record front matter and controlled-vocab.yaml, so
the result is deterministic and idempotent: two runs produce identical bytes.

Usage:
    uv run scripts/build_indexes.py            # write into the repository
    uv run scripts/build_indexes.py --out DIR  # write into DIR instead
    uv run scripts/build_indexes.py --check    # fail if any page is stale
"""

from __future__ import annotations

import argparse
import pathlib
import sys

import yaml

HEADER = "<!-- generated by scripts/build_indexes.py; do not edit -->"
SPEC = "RECORD-FORMAT.md"
VOCAB = "controlled-vocab.yaml"

TYPE_ORDER = ["dataset", "collection", "aggregator", "portal"]
ACCESS_ORDER = ["open", "registration", "on-request", "closed", "mixed"]

SUMMARY_HEADERS = [
    "ID",
    "Name",
    "Type",
    "Platform",
    "Coverage",
    "Count",
    "Access",
    "Licence",
    "Confidence",
]


def root_dir() -> pathlib.Path:
    """Repository root, resolved from this file's location."""
    return pathlib.Path(__file__).resolve().parent.parent


def load_vocabulary(root: pathlib.Path) -> list[dict]:
    path = root / "datasets" / VOCAB
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    return sorted(data["domains"], key=lambda domain: domain["sequence"])


def load_records(root: pathlib.Path) -> list[dict]:
    records = []
    for path in sorted((root / "datasets" / "records").glob("*.md")):
        text = path.read_text(encoding="utf-8")
        if not text.startswith("---\n"):
            raise ValueError(f"{path}: missing YAML front matter")
        end = text.find("\n---", 4)
        if end < 0:
            raise ValueError(f"{path}: unterminated YAML front matter")
        front = yaml.safe_load(text[4:end])
        if not isinstance(front, dict):
            raise ValueError(f"{path}: front matter is not a mapping")
        records.append(front)
    records.sort(key=lambda record: str(record.get("id", "")))
    return records


def cell(value) -> str:
    if value is None:
        return ""
    return str(value).replace("|", "\\|").replace("\n", " ")


def join_list(values) -> str:
    if not isinstance(values, list):
        return ""
    return ", ".join(str(value) for value in values)


def coverage(record: dict) -> str:
    parts = []
    for rng in record.get("spectral_coverage") or []:
        if not isinstance(rng, dict):
            continue
        region = rng.get("region") or "unstated"
        unit = rng.get("unit") or "unstated"
        parts.append(f"{region} ({unit})")
    return "; ".join(parts) or "not stated"


def count_label(record: dict) -> str:
    count = record.get("count")
    if count is None:
        return "unknown"
    qualifier = record.get("count_qualifier")
    if qualifier == "exact":
        return str(count)
    if qualifier == "gte":
        return f">={count}"
    if qualifier == "approx":
        return f"~{count}"
    return f"{count}?"


def render_table(headers: list[str], rows: list[list[str]]) -> str:
    lines = [
        "| " + " | ".join(headers) + " |",
        "|" + "|".join("---" for _ in headers) + "|",
    ]
    for row in rows:
        lines.append("| " + " | ".join(row) + " |")
    return "\n".join(lines)


def summary_row(prefix: str, record: dict, with_domains: bool = False) -> list[str]:
    record_id = record.get("id", "")
    row = [
        f"[{record_id}]({prefix}/records/{record_id}.md)",
        cell(record.get("name")),
        cell(record.get("record_type")),
    ]
    if with_domains:
        row.append(cell(join_list(record.get("domains"))))
    row.extend(
        [
            cell(join_list(record.get("platform"))),
            cell(coverage(record)),
            cell(count_label(record)),
            cell(record.get("access_class")),
            cell(record.get("licence")),
            cell(record.get("confidence")),
        ]
    )
    return row


def headers_with_domains() -> list[str]:
    return SUMMARY_HEADERS[:3] + ["Domains"] + SUMMARY_HEADERS[3:]


def in_domain(record: dict, slug: str) -> bool:
    domains = record.get("domains")
    return isinstance(domains, list) and slug in domains


def lead_domain(record: dict):
    domains = record.get("domains")
    if isinstance(domains, list) and domains:
        return domains[0]
    return None


def render_readme(records: list[dict], domains: list[dict]) -> str:
    used = [d for d in domains if any(in_domain(r, d["slug"]) for r in records)]
    memberships = sum(len(r.get("domains") or []) for r in records)

    lines = [
        HEADER,
        "",
        "# Dataset records",
        "",
        "This folder holds one Markdown record per spectral dataset, collection, aggregator "
        f"or portal. Each record starts with YAML front matter followed by prose. The format "
        f"is defined in [{SPEC}]({SPEC}); allowed values are listed in "
        f"[{VOCAB}]({VOCAB}).",
        "",
    ]
    if memberships == len(records):
        lines.append(f"{len(records)} records across {len(used)} domains.")
    else:
        lines.append(
            f"{len(records)} records, {memberships} domain memberships across "
            f"{len(used)} domains."
        )
    lines.append("")

    rows = []
    for domain in used:
        count = sum(1 for record in records if in_domain(record, domain["slug"]))
        rows.append(
            [
                str(domain["domain_id"]),
                f"[{cell(domain['name'])}](index/by-domain/{domain['slug']}.md)",
                str(count),
            ]
        )
    lines.append(render_table(["ID", "Domain", "Records"], rows))
    lines.append("")
    lines.extend(
        [
            "Counts: a bare number is exact, `>=N` is at least N, `~N` is approximate, "
            "and `N?` marks an unqualified count.",
            "",
            "Every domain lists the records that name it, and a record appears on each of "
            "its domain pages: [all records](index/all.md), [by type](index/by-type.md), "
            "[by access](index/by-access.md).",
            "",
            "To add a dataset, create `records/<dataset-id>.md` with front matter that "
            "satisfies the schema, then run `uv run scripts/build_indexes.py`.",
        ]
    )
    return "\n".join(lines) + "\n"


def render_all_page(records: list[dict]) -> str:
    lines = [
        HEADER,
        "",
        "# All records",
        "",
        f"{len(records)} records.",
        "",
        render_table(
            headers_with_domains(),
            [summary_row("..", record, with_domains=True) for record in records],
        ),
    ]
    return "\n".join(lines) + "\n"


def render_domain_page(domain: dict, records: list[dict]) -> str:
    members = [record for record in records if in_domain(record, domain["slug"])]
    leads = [record for record in members if lead_domain(record) == domain["slug"]]

    lines = [
        HEADER,
        "",
        f"# {domain['name']}",
        "",
        f"{len(members)} record(s); {len(leads)} list this as the lead domain.",
        "",
        f"Schema: [{SPEC}](../../{SPEC}) · Vocabulary: [{VOCAB}](../../{VOCAB}) · "
        "All records: [all.md](../all.md)",
        "",
        render_table(
            headers_with_domains(),
            [summary_row("../..", record, with_domains=True) for record in members],
        ),
    ]
    return "\n".join(lines) + "\n"


def render_grouped_page(
    records: list[dict], key: str, order: list[str], title: str
) -> str:
    groups: dict[str, list[dict]] = {}
    for record in records:
        groups.setdefault(str(record.get(key)), []).append(record)

    keys = [value for value in order if value in groups]
    keys.extend(sorted(value for value in groups if value not in order))

    lines = [HEADER, "", f"# {title}", "", f"{len(records)} records."]
    for value in keys:
        members = groups[value]
        lines.extend(
            [
                "",
                f"## {value} ({len(members)})",
                "",
                render_table(
                    headers_with_domains(),
                    [summary_row("..", record, with_domains=True) for record in members],
                ),
            ]
        )
    return "\n".join(lines) + "\n"


def render_all(root: pathlib.Path | None = None) -> dict[str, str]:
    """Return repo-relative path -> generated content, in a stable order."""
    root = root or root_dir()
    domains = load_vocabulary(root)
    records = load_records(root)

    pages: dict[str, str] = {
        "datasets/README.md": render_readme(records, domains),
        "datasets/index/all.md": render_all_page(records),
    }
    for domain in domains:
        if any(in_domain(record, domain["slug"]) for record in records):
            pages[f"datasets/index/by-domain/{domain['slug']}.md"] = render_domain_page(
                domain, records
            )
    pages["datasets/index/by-type.md"] = render_grouped_page(
        records, "record_type", TYPE_ORDER, "Records by type"
    )
    pages["datasets/index/by-access.md"] = render_grouped_page(
        records, "access_class", ACCESS_ORDER, "Records by access"
    )
    return pages


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out",
        type=pathlib.Path,
        help="write the pages under this directory instead of the repository",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="compare against the repository and exit non-zero if any page is stale",
    )
    args = parser.parse_args(argv)

    root = root_dir()
    pages = render_all(root)

    if args.check:
        stale = [
            rel
            for rel, content in pages.items()
            if not (root / rel).exists()
            or (root / rel).read_text(encoding="utf-8") != content
        ]
        for rel in stale:
            print(f"stale: {rel}", file=sys.stderr)
        return 1 if stale else 0

    out = args.out or root
    for rel, content in pages.items():
        path = out / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")

    print(f"wrote {len(pages)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
